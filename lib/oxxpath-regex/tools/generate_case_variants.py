#!/usr/bin/env python3
"""Generate XPath's pairwise case relation from pinned oxixml-unicode 0.1.2.

Usage: python3 tools/generate_case_variants.py PATH/TO/oxixml-unicode-0.1.2
This is an offline development tool; the library does not depend on Python.
"""

import argparse
import hashlib
from collections import defaultdict
from pathlib import Path
import re


INPUTS = {
    "src/tables/simple_case.rs": "5a33efb26d4dbb561e5b3f95d34dfe09bb66d1f8e63221e4f1ae348b1574def5",
    "src/tables/special_case.rs": "40b80a06f925d3b1c9a6251d47976e1f956ded6fbe4fb30da13b5cc2ba5d32f5",
    "src/tables/blocks.rs": "f14c34cf90ccb387b3803cde5fb9efbeb728ea4a366f3e82302d959d66bb2f82",
}
CHAR = r"'\\u\{([0-9A-F]+)\}'"


def read_pinned(root, name):
    data = (root / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != INPUTS[name]:
        raise ValueError(f"Unexpected Unicode source: {name}")
    return data.decode("utf-8")


def simple_mapping(source, name):
    body = source.split(f"static {name}:", 1)[1].split("= &[", 1)[1].split("];", 1)[0]
    return {
        int(a, 16): (int(b, 16),)
        for a, b in re.findall(r"\(" + CHAR + r", " + CHAR + r"\)", body)
    }


def generate(root):
    blocks = read_pinned(root, "src/tables/blocks.rs")
    block_names = re.findall(r'\(0x[0-9A-Fa-f]+, 0x[0-9A-Fa-f]+, "([^"]+)"\)', blocks)
    # Match the conservative parser lookup bounds in charclass.rs.
    assert len(block_names) == 346
    assert max(len(name.encode("ascii")) for name in block_names) == 48
    simple = read_pinned(root, "src/tables/simple_case.rs")
    special = read_pinned(root, "src/tables/special_case.rs")
    lower = simple_mapping(simple, "SIMPLE_LOWERCASE")
    upper = simple_mapping(simple, "SIMPLE_UPPERCASE")
    row = r"\(" + CHAR + r", &\[([^]]*)\], &\[([^]]*)\], &\[([^]]*)\]\)"
    for cp, low, _title, up in re.findall(row, special):
        lower[int(cp, 16)] = tuple(int(c, 16) for c in re.findall(CHAR, low))
        upper[int(cp, 16)] = tuple(int(c, 16) for c in re.findall(CHAR, up))

    # Context-dependent Final_Sigma cannot fire for a one-character string:
    # there is no preceding cased letter. Language-tailored rows do not apply.
    # Every nonidentity pair contains at least one mapped character. Adding
    # every one-character output covers the possible identity-mapped partner.
    candidates = set(lower) | set(upper)
    for mapping in (lower, upper):
        candidates.update(value[0] for value in mapping.values() if len(value) == 1)
    inverse_lower = defaultdict(set)
    inverse_upper = defaultdict(set)
    for cp in candidates:
        inverse_lower[lower.get(cp, (cp,))].add(cp)
        inverse_upper[upper.get(cp, (cp,))].add(cp)
    pairs = sorted(
        (cp, other)
        for cp in candidates
        for other in (
            inverse_lower[lower.get(cp, (cp,))]
            | inverse_upper[upper.get(cp, (cp,))]
        ) - {cp}
    )
    # No connected-component/transitive closure: the two inverse images are
    # united independently for each original character.
    counts = defaultdict(int)
    for cp, _ in pairs:
        counts[cp] += 1
    lines = [
        "// Generated by tools/generate_case_variants.py; do not edit.",
        "// Unicode 17.0.0, pinned oxixml-unicode 0.1.2; see UNICODE-CASE.md.",
        "// Sorted nonidentity pairs with equal full lower OR full upper mappings.",
        "// This relation is symmetric, but intentionally not transitively closed.",
        f"pub(super) const MAX_OTHER_VARIANTS: usize = {max(counts.values())};",
        "#[rustfmt::skip]",
        "pub(super) static CASE_VARIANTS: &[(char, char)] = &[",
    ]
    for offset in range(0, len(pairs), 4):
        lines.append("    " + " ".join(
            f"('\\u{{{cp:X}}}', '\\u{{{other:X}}}'),"
            for cp, other in pairs[offset:offset + 4]
        ))
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode_source", type=Path)
    parser.add_argument("--check", action="store_true", help="Check the committed output without writing")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "src/case_variants.rs"
    content = generate(args.unicode_source)
    if args.check:
        if target.read_text() != content:
            raise SystemExit("Generated case table is stale")
    else:
        target.write_text(content)
    print(f"{target.name}: {len(content.encode('utf-8'))} bytes")


if __name__ == "__main__":
    main()
